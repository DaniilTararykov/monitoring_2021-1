import raw from "./edit.json";

export type Word = { w: string; s: number; e: number; emph: boolean };
export type Caption = { start: number; end: number; words: Word[] };
export type Shot = {
  at: number;
  dur: number;
  src: number;
  speed: number | [number, number];
  zoom: [number, number];
  fx: "cut" | "flash" | "whip" | "punch" | "fade";
  /** Roll correction in degrees (clockwise), measured with scripts/tilt.py. */
  rotate?: number;
  /** Disable the handheld drift for clean, locked-off framing. */
  still?: boolean;
  /** Source file in public/ (default footage.mp4). */
  video?: string;
  /** Source-pixel point to keep centred when zoomed in (crop), clamped to the frame. */
  focus?: [number, number];
};

/** Generated by scripts/build_edit.py from src/story.json. */
export const edit = raw as unknown as {
  fps: number;
  duration: number;
  shots: Shot[];
  captions: Caption[];
  sfx: { id: string; at: number; vol: number }[];
  vo: { id: string; at: number }[];
  title: { lines: string[]; at: number; dur: number };
};

export const FPS = edit.fps;
export const DURATION = edit.duration;
export const f = (sec: number) => Math.round(sec * FPS);
