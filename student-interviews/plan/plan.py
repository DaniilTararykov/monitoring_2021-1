def overlap(a, b):
    return max(0.0, min(a[1], b[1]) - max(a[0], b[0]))

if __name__ == "__main__":
    out = {"students": STUDENTS, "questions": QUESTIONS, "videos": [], "coverage": {}}
    for v in VIDEOS:
        speech = sum(e - s for _, s, e, _ in v["clips"])
        out["videos"].append({**v, "speechSec": round(speech, 1)})
    for sid, answers in ANSWERS.items():
        total = sum(e - s for s, e in answers.values())
        used_q = {}
        for q, span in answers.items():
            used = sum(overlap(span, (s, e)) for v in VIDEOS for st, s, e, _ in v["clips"] if st == sid)
            used_q[q] = min(1.0, used / (span[1] - span[0]))
        covered = sum((answers[q][1] - answers[q][0]) * f for q, f in used_q.items())
        out["coverage"][sid] = {"answersSec": round(total, 1), "coveredPct": round(100 * covered / total), "byQuestion": {q: round(100 * f) for q, f in used_q.items()}}
    json.dump(out, open("plan.json", "w"), ensure_ascii=False, indent=1)
    for v in out["videos"]:
        print(v["id"], v["speechSec"], v["title"])
    for sid, c in out["coverage"].items():
        print(sid, c["coveredPct"], c["byQuestion"])
